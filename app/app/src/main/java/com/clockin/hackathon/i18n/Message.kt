/** One-pass substitution: user text containing {0} is never interpreted again. */
internal fun Message.format(language: String, vararg args: Any?): String {
    val template = if (language == "en") english else french
    return Regex("\\{(\\d+)\\}").replace(template) { match ->
        val index = match.groupValues[1].toInt()
        require(index < args.size) { "Missing argument $index for $name" }
        args[index].toString()
    }
}

internal fun tr(message: Message, vararg args: Any?): String = message.format(AppLanguage.code, *args)

/** Re-render app-owned errors already raised before a language switch. */
internal fun localizeError(text: String): String = Message.entries.firstOrNull {
    it.french == text || it.english == text
}?.let { tr(it) } ?: text
